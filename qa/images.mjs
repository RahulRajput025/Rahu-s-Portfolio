import sharp from 'sharp'
import { readdirSync, writeFileSync, rmSync, mkdirSync } from 'node:fs'
// portrait → crisp webp (1122w = source width, + 720w for phones) + tiny blur placeholder
const src = 'source-assets/rahul.png'
await sharp(src).webp({ quality: 88 }).toFile('public/rahul-1122.webp')
await sharp(src).resize(720, 900, { fit: 'cover' }).webp({ quality: 84 }).toFile('public/rahul-720.webp')
for (const f of ['public/rahul-1000.webp', 'public/rahul-600.webp']) { try { rmSync(f) } catch {} }
const tiny = await sharp(src).resize(24, 30, { fit: 'cover' }).blur(1).jpeg({ quality: 50 }).toBuffer()
writeFileSync('src/data/portraitBlur.ts', `/** 24px blurred placeholder painted before the portrait arrives (generated by qa/images.mjs) */\nexport const PORTRAIT_BLUR = 'data:image/jpeg;base64,${tiny.toString('base64')}'\n`)
// product screenshots: originals are 2880×1800 (desktop) and 780×1688 (phone), captured at 2× DPR
rmSync('public/shots', { recursive: true, force: true })
mkdirSync('public/shots', { recursive: true })
for (const f of readdirSync('qa/shots-src')) {
  const id = f.replace('.webp', '')
  const desktop = f.includes('desktop')
  if (desktop) {
    await sharp(`qa/shots-src/${f}`).resize(1440).webp({ quality: 84 }).toFile(`public/shots/${id}-1440.webp`)
    await sharp(`qa/shots-src/${f}`).resize(800).webp({ quality: 80 }).toFile(`public/shots/${id}-800.webp`)
  } else {
    await sharp(`qa/shots-src/${f}`).resize(640).webp({ quality: 84 }).toFile(`public/shots/${id}-640.webp`)
    await sharp(`qa/shots-src/${f}`).resize(360).webp({ quality: 80 }).toFile(`public/shots/${id}-360.webp`)
  }
}
console.log('images done')
